MAX_WORDS_PER_CUE = 8
MIN_WORDS_PER_CUE = 4
MAX_CHARS_PER_CUE = 45
MIN_DURATION_S = 1.0
PUNCTUATION_CUT = (".", "?", "!", ":", ";", "—")


def format_srt_time(seconds: float) -> str:
    seconds = max(0.0, float(seconds))
    total_sec = int(seconds)
    millis = int(round((seconds - total_sec) * 1000))
    if millis == 1000:
        total_sec += 1
        millis = 0
    hours = total_sec // 3600
    minutes = (total_sec % 3600) // 60
    secs = total_sec % 60
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{millis:03d}"


def normalizar(texto: str) -> str:
    """Normaliza texto para comparación tolerante en SequenceMatcher."""
    t = unicodedata.normalize("NFKD", texto).encode("ascii", "ignore").decode("ascii")
    t = re.sub(r"[^\w\s]", "", t.lower())
    return t.strip()


def alinear_guion_con_whisper(palabras_guion: list[str], words_whisper: list[dict]) -> list[dict]:
    """
    Empareja las palabras del guion con los timestamps detectados por Whisper.
    Devuelve lista de dicts: {'word': palabra_guion, 'start': float, 'end': float}
    """
    a = [normalizar(p) for p in palabras_guion]
    b = [normalizar(w["word"]) for w in words_whisper]

    matcher = SequenceMatcher(a=a, b=b, autojunk=False)
    o2w = {}
    for bloque in matcher.get_matching_blocks():
        for k in range(bloque.size):
            o2w[bloque.a + k] = bloque.b + k

    resultado = []
    num_a = len(palabras_guion)
    num_b = len(words_whisper)

    for i in range(num_a):
        w_idx = o2w.get(i)
        if w_idx is not None and 0 <= w_idx < num_b:
            start = words_whisper[w_idx]["start"]
            end = words_whisper[w_idx]["end"]
        else:
            # Buscar el emparejado más cercano
            start = None
            end = None
            for delta in range(1, max(i, num_a - i) + 1):
                for cand in (i - delta, i + delta):
                    if cand in o2w and 0 <= o2w[cand] < num_b:
                        ref_w = words_whisper[o2w[cand]]
                        start = ref_w["start"]
                        end = ref_w["end"]
                        break
                if start is not None:
                    break
            if start is None:
                start = 0.0
                end = 1.0

        resultado.append({
            "word": palabras_guion[i],
            "start": float(start),
            "end": float(end),
        })

    # Asegurar orden estrictamente monótono en start
    for i in range(1, len(resultado)):
        if resultado[i]["start"] < resultado[i - 1]["start"]:
            resultado[i]["start"] = resultado[i - 1]["start"] + 0.1
        if resultado[i]["end"] <= resultado[i]["start"]:
            resultado[i]["end"] = resultado[i]["start"] + 0.3

    return resultado


def agrupar_en_cues(palabras_alineadas: list[dict]) -> list[dict]:
    cues = []
    current_cue = []
    cue_start = None

    for i, w in enumerate(palabras_alineadas):
        palabra = w["word"].strip()
        if not palabra:
            continue

        if not current_cue:
            cue_start = w["start"]

        current_cue.append(palabra)
        current_text = " ".join(current_cue)
        cue_end = w["end"]

        es_fin_de_frase = any(palabra.endswith(p) for p in PUNCTUATION_CUT)
        num_palabras = len(current_cue)
        num_caracteres = len(current_text)

        es_ultimo = (i == len(palabras_alineadas) - 1)
        debe_cortar = (
            (es_fin_de_frase and num_palabras >= MIN_WORDS_PER_CUE)
            or (num_palabras >= MAX_WORDS_PER_CUE)
            or (num_caracteres >= MAX_CHARS_PER_CUE)
            or es_ultimo
        )

        if debe_cortar:
            dur = cue_end - cue_start
            if dur < MIN_DURATION_S and not es_ultimo:
                cue_end = cue_start + MIN_DURATION_S

            cues.append({
                "start": cue_start,
                "end": cue_end,
                "text": current_text,
            })
            current_cue = []
            cue_start = None

    return cues


def main():
    print("=" * 65)
    print(" GENERADOR DE SUBTÍTULOS .SRT CON WHISPER Y GUION (ADR-030)")
    print("=" * 65)

    if not VIDEO_VOZ.exists():
        print(f"[ERROR] No existe el archivo: {VIDEO_VOZ}")
        sys.exit(1)

    OUTPUT_SRT.parent.mkdir(parents=True, exist_ok=True)

    print(f"Vídeo fuente: {VIDEO_VOZ.name}")
    print("Cargando modelo Whisper 'base'...")
    model = whisper.load_model("base")

    print(f"Transcribiendo con Whisper para obtener timestamps por palabra...")
    result = model.transcribe(str(VIDEO_VOZ), language="en", word_timestamps=True)

    words_whisper = []
    for seg in result.get("segments", []):
        for w in seg.get("words", []):
            words_whisper.append({
                "word": w.get("word", ""),
                "start": float(w.get("start", 0.0)),
                "end": float(w.get("end", 0.0)),
            })

    print(f"Palabras detectadas por Whisper: {len(words_whisper)}")

    # Extraer palabras del guion original
    texto_guion = " ".join(GUION_COMPLETO)
    palabras_guion = texto_guion.split()
    print(f"Palabras del guion oficial:      {len(palabras_guion)}")

    print("\nAlineando texto del guion con los tiempos de Whisper (SequenceMatcher)...")
    palabras_alineadas = alinear_guion_con_whisper(palabras_guion, words_whisper)

    cues = agrupar_en_cues(palabras_alineadas)
    print(f"Total cues generados: {len(cues)}")

    lineas_srt = []
    for idx, cue in enumerate(cues, 1):
        t_ini = format_srt_time(cue["start"])
        t_fin = format_srt_time(cue["end"])
        lineas_srt.append(f"{idx}\n{t_ini} --> {t_fin}\n{cue['text']}\n")

    contenido = "\n".join(lineas_srt)
    OUTPUT_SRT.write_text(contenido, encoding="utf-8")

    print(f"\n[ÉXITO] Archivo SRT generado con ortografía impecable:\n  -> {OUTPUT_SRT.resolve()}")
    print("\n--- Vista previa de los primeros 5 cues (Texto oficial) ---")
    for cue in cues[:5]:
        print(f"  [{format_srt_time(cue['start'])} --> {format_srt_time(cue['end'])}] {cue['text']}")

    print("\n--- Verificación de términos clave ---")
    contenido_lower = contenido.lower()
    print(f"  Contiene 'supabase':    {'supabase' in contenido_lower}")
    print(f"  Contiene 'superbase':   {'superbase' in contenido_lower} (debe ser False)")
    print(f"  Contiene 'postgresql':  {'postgresql' in contenido_lower}")
    print(f"  Contiene '.env':        {'.env' in contenido_lower}")
    print("=" * 65)


if __name__ == "__main__":
    main()
