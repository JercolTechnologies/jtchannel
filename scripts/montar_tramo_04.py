# -*- coding: utf-8 -*-
"""
Montaje completo del Tramo 04 (Clip 05 con voz Nova):
1. Genera los 2 bloques de narración con 'gpt-4o-mini-tts' (voz 'nova') con tono enérgico y amigable.
2. Mide la duración exacta de cada bloque de audio.
3. Aplica sincronización dinámica:
   - Bloque 1 arranca en t = 0.5s (Supabase navegación y Schema Visualizer).
   - Jump cut en t = 20.0s (salto a Antigravity sin los 4s muertos).
   - Bloque 2 arranca en t = 20.3s (Antigravity datos y cierre).
   - Corte final del vídeo recortado exactamente a fin_de_voz + 1.0s de margen.
4. Mezcla pistas de audio sincronizadas.
5. Muxea y aplica normalización con doble pasada 'loudnorm' (-14 LUFS) con '-c:v copy'.
6. Limpia archivos temporales y deja únicamente 'output/tramo_04_completo.mp4'.
"""

import json
import os
import subprocess
import sys
from pathlib import Path
from dotenv import load_dotenv
from openai import OpenAI

BLOQUES_GUION = [
    {
        "id": "b1_supabase_schema",
        "cue_sec": 0.5,
        "text": (
            "Now let's head over to Supabase to see the magic live. We open our project, "
            "jump into the Database tab, and open the Schema Visualizer... and look at that! "
            "All three tables, foreign keys, and relations were created completely autonomously in PostgreSQL."
        ),
    },
    {
        "id": "b2_antigravity_match_outro",
        "cue_sec": 20.3,
        "text": (
            "Back in Antigravity, we can see the seed data generated by the agent matches our schema perfectly. "
            "Giving your agent direct MCP superpowers to manage your database is that simple. "
            "Hit subscribe for more agent workflows, and see you in the next one!"
        ),
    },
]

INSTRUCCIONES_TONO = (
    "Speak in an enthusiastic, cheerful, friendly, and energetic conversational tone like talking with developer friends. "
    "Natural upbeat pacing with clear pauses, engaging and relatable, no stiff lecture monotone."
)

CLIP_05_RAW = Path("clips/05_showing_the_schema_created.mp4")
OUTPUT_DIR = Path("output")


def medir_duracion(ruta: Path) -> float:
    cmd = [
        "ffprobe", "-v", "error",
        "-show_entries", "format=duration",
        "-of", "default=noprint_wrappers=1:nokey=1",
        str(ruta),
    ]
    res = subprocess.run(cmd, capture_output=True, text=True, check=True)
    return float(res.stdout.strip())


def sintetizar_bloques(client: OpenAI, audio_dir: Path, regenerar: bool = False) -> list[dict]:
    audio_dir.mkdir(parents=True, exist_ok=True)
    bloques_generados = []

    print("\n--- 1. Generando audios TTS con gpt-4o-mini-tts (Voz: Nova) ---")
    for b in BLOQUES_GUION:
        ruta_mp3 = audio_dir / f"{b['id']}.mp3"

        if ruta_mp3.exists() and not regenerar:
            print(f"Reutilizando audio existente '{b['id']}'...", end=" ", flush=True)
        else:
            print(f"Sintetizando bloque '{b['id']}'...", end=" ", flush=True)
            resp = client.audio.speech.create(
                model="gpt-4o-mini-tts",
                voice="nova",
                input=b["text"],
                instructions=INSTRUCCIONES_TONO,
                response_format="mp3",
            )
            resp.write_to_file(ruta_mp3)

        dur = medir_duracion(ruta_mp3)
        print(f"OK ({dur:.2f} s)")
        bloques_generados.append({**b, "path": ruta_mp3, "duration": dur})

    return bloques_generados


def cortar_y_concatenar_video_dinamico(dur_audio2: float, salida_video: Path) -> float:
    """
    Corta el vídeo asegurando que la Parte 2 termine exactamente 1.0s después del audio 2.
    """
    print("\n--- 2. Cortando vídeo con margen final dinámico (+1.0s tras la voz) ---")

    p1_dur = 20.0  # de 2.0s a 22.0s
    cue2 = 0.3
    p2_dur = round(cue2 + dur_audio2 + 1.0, 2)
    # No exceder el metraje limpio disponible (15.5s)
    if p2_dur > 15.5:
        p2_dur = 15.5

    print(f"Parte 1 (Supabase): [2.0s -> 22.0s] (duración: {p1_dur:.2f}s)")
    print(f"Parte 2 (Antigravity + vuelta a Supabase): [26.0s -> {26.0 + p2_dur:.2f}s] (duración: {p2_dur:.2f}s)")
    print(f"  -> Margen final exacto tras última palabra: {p2_dur - cue2 - dur_audio2:.2f} s")

    temp_dir = OUTPUT_DIR / "temp_tramo_04_montaje"
    temp_dir.mkdir(parents=True, exist_ok=True)
    p1_mp4 = temp_dir / "p1.mp4"
    p2_mp4 = temp_dir / "p2.mp4"

    cmd_p1 = [
        "ffmpeg", "-y", "-v", "error",
        "-ss", "2.0",
        "-i", str(CLIP_05_RAW),
        "-t", str(p1_dur),
        "-c:v", "libx264", "-preset", "fast", "-crf", "18",
        "-r", "60", "-pix_fmt", "yuv420p",
        "-an",
        str(p1_mp4),
    ]
    subprocess.run(cmd_p1, check=True)

    cmd_p2 = [
        "ffmpeg", "-y", "-v", "error",
        "-ss", "26.0",
        "-i", str(CLIP_05_RAW),
        "-t", str(p2_dur),
        "-c:v", "libx264", "-preset", "fast", "-crf", "18",
        "-r", "60", "-pix_fmt", "yuv420p",
        "-an",
        str(p2_mp4),
    ]
    subprocess.run(cmd_p2, check=True)

    concat_txt = temp_dir / "concat.txt"
    concat_txt.write_text(
        f"file '{p1_mp4.resolve().as_posix()}'\nfile '{p2_mp4.resolve().as_posix()}'\n",
        encoding="utf-8"
    )

    cmd_concat = [
        "ffmpeg", "-y", "-v", "error",
        "-f", "concat", "-safe", "0",
        "-i", str(concat_txt),
        "-c:v", "copy",
        str(salida_video),
    ]
    subprocess.run(cmd_concat, check=True)

    # Limpieza trozos
    p1_mp4.unlink(missing_ok=True)
    p2_mp4.unlink(missing_ok=True)
    concat_txt.unlink(missing_ok=True)
    temp_dir.rmdir()

    dur_total = medir_duracion(salida_video)
    print(f"Vídeo recortado dinámico generado: {salida_video.name} ({dur_total:.2f} s)")
    return dur_total


def mezclar_pista_audio(bloques: list[dict], dur_total_video: float, salida_audio: Path) -> None:
    print("\n--- 3. Mezclando pistas de voz sincronizadas ---")
    cue1 = bloques[0]["cue_sec"]
    cue2 = bloques[1]["cue_sec"]

    print(f"Audio 1 inicia en t = {cue1:.2f} s")
    print(f"Audio 2 inicia en t = {cue2:.2f} s")

    entradas = ["-i", str(bloques[0]["path"]), "-i", str(bloques[1]["path"])]
    delay1_ms = int(cue1 * 1000)
    delay2_ms = int(cue2 * 1000)

    filtro = (
        f"[0:a]adelay={delay1_ms}|{delay1_ms}[a0];"
        f"[1:a]adelay={delay2_ms}|{delay2_ms}[a1];"
        f"[a0][a1]amix=inputs=2:dropout_transition=0:normalize=0,"
        f"apad=whole_dur={dur_total_video}[aout]"
    )

    cmd = [
        "ffmpeg", "-y", "-v", "error",
        *entradas,
        "-filter_complex", filtro,
        "-map", "[aout]",
        "-c:a", "libmp3lame",
        "-b:a", "192k",
        str(salida_audio),
    ]
    subprocess.run(cmd, check=True)
    dur_audio_final = medir_duracion(salida_audio)
    print(f"Pista de voz completa mezclada: {salida_audio.name} ({dur_audio_final:.2f} s)")


def normalizar_master_loudnorm(video_crudo: Path, video_final: Path) -> None:
    print("\n--- 4. Normalizando sonoridad del master (-14 LUFS, doble pasada) ---")
    filtro_base = "loudnorm=I=-14:LRA=7:TP=-1.5"

    cmd_medir = [
        "ffmpeg", "-hide_banner", "-nostats", "-y",
        "-i", str(video_crudo),
        "-vn",
        "-af", f"{filtro_base}:print_format=json",
        "-f", "null", "-",
    ]
    r = subprocess.run(cmd_medir, capture_output=True, text=True)
    salida = r.stderr or ""
    ini, fin = salida.rfind("{"), salida.rfind("}")
    if ini == -1 or fin == -1:
        print("[AVISO] Medición falló, aplicando pasada simple.")
        filtro_aplicar = filtro_base
    else:
        datos = json.loads(salida[ini:fin + 1])
        filtro_aplicar = (
            f"{filtro_base}:measured_I={datos['input_i']}:measured_LRA={datos['input_lra']}:"
            f"measured_TP={datos['input_tp']}:measured_thresh={datos['input_thresh']}:"
            f"offset={datos['target_offset']}:linear=true"
        )

    cmd_aplicar = [
        "ffmpeg", "-y", "-v", "error",
        "-i", str(video_crudo),
        "-c:v", "copy",
        "-af", filtro_aplicar,
        "-c:a", "aac",
        "-b:a", "192k",
        "-ar", "48000",
        str(video_final),
    ]
    subprocess.run(cmd_aplicar, check=True)
    print(f"Master normalizado con éxito: {video_final.name}")


def main():
    load_dotenv()
    api_key = os.getenv("OPENAI_API_KEY")
    if not api_key:
        print("[ERROR] Falta OPENAI_API_KEY en .env")
        sys.exit(1)

    client = OpenAI(api_key=api_key)

    # 1. Audios
    audio_dir = OUTPUT_DIR / "audios_tramo_04"
    bloques = sintetizar_bloques(client, audio_dir)

    dur_a2 = bloques[1]["duration"]

    # 2. Cortar vídeo dinámicamente según la duración del audio 2
    video_editado = OUTPUT_DIR / "tramo_04_editado_dinamico.mp4"
    dur_total = cortar_y_concatenar_video_dinamico(dur_a2, video_editado)

    # 3. Mezcla de audio
    pista_audio = OUTPUT_DIR / "tramo_04_audio_mix.mp3"
    mezclar_pista_audio(bloques, dur_total, pista_audio)

    # 4. Mux inicial
    video_mux = OUTPUT_DIR / "tramo_04_mux_temp.mp4"
    print("\n--- Uniendo vídeo con pista de voz ---")
    cmd_mux = [
        "ffmpeg", "-y", "-v", "error",
        "-i", str(video_editado),
        "-i", str(pista_audio),
        "-vf", "drawbox=enable='gte(t, 20.0)':x=0:y=305:w=320:h=635:color=0x161616:t=fill",
        "-c:v", "libx264", "-preset", "fast", "-crf", "17",
        "-pix_fmt", "yuv420p",
        "-c:a", "copy",
        "-shortest",
        str(video_mux),
    ]
    subprocess.run(cmd_mux, check=True)

    # 5. Normalizar master a -14 LUFS
    video_final = OUTPUT_DIR / "tramo_04_completo.mp4"
    normalizar_master_loudnorm(video_mux, video_final)

    # 6. Limpieza: borrar temporales y dejar solo los completos
    video_mux.unlink(missing_ok=True)
    video_editado.unlink(missing_ok=True)
    (OUTPUT_DIR / "tramo_04_editado.mp4").unlink(missing_ok=True)

    # 7. Verificación final ffprobe
    print("\n" + "=" * 60)
    print(" VERIFICACIÓN TÉCNICA DEL MASTER FINAL (ffprobe)")
    print("=" * 60)
    cmd_info = [
        "ffprobe", "-v", "error",
        "-show_entries", "stream=codec_name,width,height,r_frame_rate,duration,sample_rate,channels",
        "-of", "json",
        str(video_final),
    ]
    res = subprocess.run(cmd_info, capture_output=True, text=True, check=True)
    print(res.stdout)

    # Medir LUFS del vídeo final
    cmd_lufs = [
        "ffmpeg", "-hide_banner", "-nostats",
        "-i", str(video_final),
        "-vn",
        "-af", "loudnorm=I=-14:LRA=7:TP=-1.5:print_format=json",
        "-f", "null", "-",
    ]
    r_lufs = subprocess.run(cmd_lufs, capture_output=True, text=True)
    out_l = r_lufs.stderr or ""
    i1, i2 = out_l.rfind("{"), out_l.rfind("}")
    if i1 != -1 and i2 != -1:
        d_lufs = json.loads(out_l[i1:i2 + 1])
        print(f"Sonoridad final alcanzada: {d_lufs.get('input_i')} LUFS (Target: -14.0 LUFS)")

    print(f"\n[ÉXITO] Archivo final listo en: {video_final}\n")


if __name__ == "__main__":
    main()
